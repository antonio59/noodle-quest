import type { WordEntry } from './schema';
import { normalise } from './filters';

function w(answer: string, overrides: Partial<Omit<WordEntry, 'id' | 'answer' | 'normalised' | 'length'>> = {}): WordEntry {
  return {
    id: `gb-${normalise(answer)}`,
    answer,
    normalised: normalise(answer),
    locale: 'en-GB',
    length: answer.length,
    tags: overrides.tags ?? [],
    difficulty: overrides.difficulty ?? 1,
    frequency: overrides.frequency ?? 500,
    banned: overrides.banned ?? false,
    variants: overrides.variants,
  };
}

